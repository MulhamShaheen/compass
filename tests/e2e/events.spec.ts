import { expect, test } from "@playwright/test";

test("events work with a quest and calendar-file export without Google", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Load sample character" }).click();
  await expect(page.getByRole("link", { name: /Run a 10K/ })).toBeVisible();
  await page.getByRole("link", { name: /Run a 10K/ }).click();
  const questPoints = page.getByTestId("quest-points");
  const before = Number(await questPoints.innerText());
  await page.getByRole("link", { name: "Add event to this quest" }).click();
  const add = page.getByRole("form", { name: "Add event" });
  await expect(add.getByLabel("Quest (optional)")).toHaveValue(/.+/);
  const title = "Training walk, then stretch";
  await add.getByLabel("Event title").fill(title);
  await add.getByLabel("Starts", { exact: true }).fill("2025-11-25T18:00");
  await add.getByLabel("Ends", { exact: true }).fill("2025-11-25T18:30");
  await add.getByRole("button", { name: "Save event" }).click();
  const card = page.getByRole("listitem").filter({ has: page.getByRole("heading", { name: title }) });
  await expect(card).toContainText("Planned");
  const url = await card.getByRole("link", { name: "Download .ics", exact: true }).getAttribute("href");
  const ics = await page.request.get(url!);
  expect(ics.ok()).toBe(true);
  expect(ics.headers()["content-type"]).toContain("text/calendar");
  expect(await ics.text()).toContain("SUMMARY:Training walk\\, then stretch");
  await card.getByRole("button", { name: "Complete event", exact: true }).click();
  await expect(card).toContainText("5 points");
  await card.getByRole("link", { name: "Run a 10K" }).click();
  await expect(questPoints).toHaveText(String(before + 5));
  await page.getByRole("link", { name: title }).click();
  await card.getByRole("button", { name: "Edit event" }).click();
  const edit = card.getByRole("form", { name: "Edit event" });
  await edit.getByLabel("Checkpoint (optional)").selectOption({ index: 1 });
  await edit.getByRole("button", { name: "Save changes" }).click();
  await expect(card).toContainText("Points recorded in checkpoint");
  await card.getByRole("button", { name: "Reopen event" }).click();
  await expect(card).toContainText("Planned");
  await card.getByRole("button", { name: "Remove event" }).click();
  await card.getByRole("button", { name: "Keep event" }).click();
  await card.getByRole("button", { name: "Remove event" }).click();
  await card.getByRole("button", { name: "Delete event" }).click();
  await expect(card).toHaveCount(0);
});
